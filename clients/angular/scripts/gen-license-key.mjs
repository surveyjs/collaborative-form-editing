// Bakes SURVEYJS_LICENSE_KEY from the environment into src/license-key.ts.
// Runs automatically before `ng build` / `ng serve` (npm pre-hooks) — the
// Angular builder has no import.meta.env equivalent for arbitrary env vars.
// Falls back to the shared .env at the repo root (same file the Vite clients
// read via envDir) when the variable is not set in the environment.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));

function readDotEnv(name) {
    const envFile = path.resolve(here, "..", "..", "..", ".env");
    if (!fs.existsSync(envFile)) return "";
    for (const line of fs.readFileSync(envFile, "utf8").split(/\r?\n/)) {
        const m = line.match(/^\s*(?:export\s+)?([\w.]+)\s*=\s*(.*)\s*$/);
        if (m && m[1] === name) return m[2].replace(/^(["'])(.*)\1$/, "$2");
    }
    return "";
}

const key = process.env.SURVEYJS_LICENSE_KEY || readDotEnv("SURVEYJS_LICENSE_KEY");
const file = path.resolve(here, "..", "src", "license-key.ts");
const content =
    "// GENERATED by scripts/gen-license-key.mjs — do not edit, set SURVEYJS_LICENSE_KEY instead.\n" +
    `export const SURVEYJS_LICENSE_KEY = ${JSON.stringify(key)};\n`;

if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) {
    fs.writeFileSync(file, content);
}
